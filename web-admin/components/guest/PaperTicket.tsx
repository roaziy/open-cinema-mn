import type { TicketView } from '@open-cinema/shared';
import { ubDate } from '@open-cinema/shared';
import QRCode from 'qrcode';
import type { ReactNode } from 'react';
import { Poster } from '@/components/ui/Poster';
import { clockUb, dayMonth, weekdayMn } from '@/lib/format';
import { avoidOrange, readableOn } from '@/lib/tone';

const NOTCH = 12;
const notchMask = (y: string) =>
  [0, 100]
    .map(
      (x) =>
        `radial-gradient(circle ${NOTCH}px at ${x}% ${y}, #0000 ${NOTCH - 0.5}px, #000 ${NOTCH}px)`,
    )
    .join(',');

/** Rendered on the server, so the token never needs a script and the QR works as soon as the page does. */
async function qrSvg(token: string): Promise<string> {
  return QRCode.toString(token, {
    type: 'svg',
    errorCorrectionLevel: 'M',
    margin: 0,
    color: { dark: '#17161a', light: '#0000' },
  });
}

/**
 * The only light surface in the product: a paper ticket in two halves joined by a perforation.
 * The top half carries the film (in its own tone) and the huge seat code, the stub carries the QR.
 */
export async function PaperTicket({
  ticket,
  wallet,
}: {
  ticket: TicketView;
  /** The "Add to Apple Wallet" control, when it should show for this ticket. */
  wallet?: ReactNode;
}) {
  const t = ticket;
  const live = t.status === 'valid';
  const tone = avoidOrange(t.movie.tone);
  const onTone = readableOn(tone);
  const day = ubDate(t.showtime.startsAt);
  const seat = `${t.seat.rowLabel}${t.seat.number}`;
  const svg = live ? await qrSvg(t.qrToken) : null;

  return (
    <article
      aria-label={`Билет, суудал ${seat}`}
      className="mx-auto w-full max-w-[360px] text-[#17161a]"
    >
      <div
        className="rounded-t-[20px] bg-[#f2ede4] pb-5"
        style={{
          WebkitMaskImage: notchMask('100%'),
          maskImage: notchMask('100%'),
          maskComposite: 'intersect',
          WebkitMaskComposite: 'source-in',
        }}
      >
        <div
          className="flex items-center gap-3 rounded-t-[20px] px-5 py-4"
          style={{ background: tone, color: onTone }}
        >
          <Poster
            src={t.movie.posterUrl}
            title={t.movie.title}
            tone={tone}
            className="h-[72px] w-12 rounded-[8px]"
          />
          <div className="min-w-0">
            <p className="text-[19px] leading-tight font-semibold">{t.movie.title}</p>
            <p className="mt-1 text-[14px] opacity-80">
              {t.showtime.format} · {t.movie.ageRating}
            </p>
          </div>
        </div>

        <div className="flex items-end justify-between gap-4 px-5 pt-5">
          <div>
            <p className="text-[13px] text-[#6b665e]">Суудал</p>
            <p
              className={`text-[96px] leading-[0.85] font-semibold tracking-[-0.04em] tabular-nums ${live ? '' : 'line-through opacity-40'}`}
            >
              {seat}
            </p>
          </div>
          <dl className="pb-1 text-right">
            <dt className="text-[13px] text-[#6b665e]">
              {weekdayMn(day)}, {dayMonth(day)}
            </dt>
            <dd className="text-[34px] leading-none font-semibold tabular-nums">
              {clockUb(t.showtime.startsAt)}
            </dd>
            <dd className="mt-2 text-[15px] font-medium">{t.hallName}</dd>
          </dl>
        </div>
      </div>

      <div
        className="rounded-b-[20px] border-t-2 border-dashed border-[#c9c2b4] bg-[#f2ede4] px-5 pt-6 pb-5"
        style={{
          WebkitMaskImage: notchMask('0'),
          maskImage: notchMask('0'),
          maskComposite: 'intersect',
          WebkitMaskComposite: 'source-in',
        }}
      >
        {svg ? (
          <div
            role="img"
            aria-label="Тасалбарын QR код"
            className={`mx-auto size-[216px] [&>svg]:size-full ${t.usedAt ? 'opacity-30' : ''}`}
            // biome-ignore lint/security/noDangerouslySetInnerHtml: SVG generated by the qrcode library from our own signed token
            dangerouslySetInnerHTML={{ __html: svg }}
          />
        ) : (
          <p className="py-10 text-center text-[17px] font-semibold text-[#8a2d2d]">
            Тасалбар цуцлагдсан
          </p>
        )}
        {t.usedAt && (
          <p className="mt-3 text-center text-[15px] font-medium text-[#6b665e]">
            {clockUb(t.usedAt)}-д орсон
          </p>
        )}
        <p className="mt-4 text-center text-[13px] text-[#6b665e] tabular-nums">
          {t.orderNo} · Код{' '}
          <span className="font-semibold tracking-[0.12em] text-[#17161a]">{t.checkCode}</span>
        </p>
        {live && wallet}
      </div>
    </article>
  );
}
